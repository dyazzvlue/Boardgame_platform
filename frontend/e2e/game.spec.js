import { expect, test } from '@playwright/test'

test('a waiting-room seat survives refresh and explicit departure clears recovery', async ({ page }) => {
  await page.goto('/game')
  await expect(page.getByRole('button', { name: '创建房间', exact: true })).toBeEnabled()
  await page.getByPlaceholder('你的名字').first().fill('browser-player')
  await page.getByRole('button', { name: '创建房间', exact: true }).click()
  await expect(page).toHaveURL(/\/game\/[A-Z0-9]{6}$/)
  const roomURL = page.url()
  await expect(page.getByRole('heading', { name: /^房间:/ })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: /^房间:/ })).toBeVisible()
  await expect(page).toHaveURL(roomURL)
  await expect(page.getByText('browser-player', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '无法恢复房间' })).toHaveCount(0)
  await page.getByRole('button', { name: '离开房间，返回大厅' }).click()
  await expect(page).toHaveURL(/\/game$/)
  await page.reload()
  await expect(page).toHaveURL(/\/game$/)
  await expect(page.getByRole('heading', { name: /游戏大厅/ })).toBeVisible()
})

test('a shared room URL without credentials asks for an identity', async ({ page }) => {
  await page.goto('/game/ABC123')
  await expect(page).toHaveURL(/\/game\?room=ABC123$/)
  await expect(page.getByPlaceholder('6位房间码')).toHaveValue('ABC123')
  await expect(page.getByRole('button', { name: '加入游戏', exact: true })).toBeVisible()
})

test('a second page can take over without the old page reconnecting repeatedly', async ({ page, context }) => {
  await page.goto('/game')
  await expect(page.getByRole('button', { name: '创建房间', exact: true })).toBeEnabled()
  await page.getByPlaceholder('你的名字').first().fill('takeover-player')
  await page.getByRole('button', { name: '创建房间', exact: true }).click()
  await expect(page).toHaveURL(/\/game\/[A-Z0-9]{6}$/)
  const roomURL = page.url()
  const credential = await page.evaluate(() => sessionStorage.getItem('boardgame.resume'))
  const replacement = await context.newPage()
  await replacement.addInitScript(value => sessionStorage.setItem('boardgame.resume', value), credential)
  await replacement.goto(roomURL)
  await expect(replacement.getByRole('heading', { name: /^房间:/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: '无法恢复房间' })).toBeVisible()
  await expect(page.getByText('连接已在另一页面恢复，请在该页面继续游戏', { exact: true })).toBeVisible()
  await expect(replacement.getByRole('button', { name: '添加AI', exact: true })).toBeEnabled()
  await replacement.getByRole('button', { name: '离开房间，返回大厅' }).click()
  await replacement.close()
})
